declare(strict_types=1);

namespace WebtechSolutions\AiCore\Controller\Adminhtml\AiLog;

use Magento\Backend\App\Action;
use Magento\Backend\App\Action\Context;
use Magento\Framework\View\Result\PageFactory;
use Magento\Framework\App\Action\HttpGetActionInterface;

class Index extends Action implements HttpGetActionInterface
{
    public const ADMIN_RESOURCE = 'WebtechSolutions_AiCore::ai_logs';

    public function __construct(
        Context $context,
        protected readonly PageFactory $resultPageFactory
    ) {
        parent::__construct($context);
    }

    public function execute(): \Magento\Framework\View\Result\Page
    {
        $resultPage = $this->resultPageFactory->create();
        $resultPage->setActiveMenu('WebtechSolutions_AiCore::ai_logs');
        $resultPage->getConfig()->getTitle()->prepend(__('AI Logs'));
        return $resultPage;
    }
}
